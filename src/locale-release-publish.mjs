// release:publish — publish a release:build package as the GitHub Release
// locale/<patch>-<n> on the ackness/poe2-zh-cn-stats main commit that built it.
// Assets: pobr-locale-<patch>.zip (the build's zip, byte for byte), receipt.json
// and SHA256SUMS. <n> starts at 1 per patch, is one above the highest remote
// locale/<patch>-<n> tag, and a commit never gets a second number.
//
// Without --yes nothing is tagged, pushed or released: the package is built (or
// with --reuse, the existing build of HEAD is verified), staged under
// .cache/release/publish/ and the exact commands are printed. A dry run reports
// preflight problems (dirty tree, HEAD not on origin/main, network failures);
// --yes refuses on any of them. A failed step is resumed by rerunning.
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { strictJson } from './strict-json.mjs';
import { readZip } from './stored-zip.mjs';
import {
  REPOSITORY, RECEIPT_SCHEMA, ROOT, assetName, build, defaultConfig, git, loadConfig, log, pin, producerIdentity,
  require, samePin, sha256sums, targetName,
} from './locale-release.mjs';

export const REMOTE = 'origin';
export const BRANCH = 'main';
export const TAG_PREFIX = 'locale/';
const MARKER = '.release-publish';
const say = message => log('release:publish', message);

// --- pure parts (no network, no Git) -------------------------------------------------------------

export const tagName = (patch, sequence) => `${TAG_PREFIX}${patch}-${sequence}`;

// {tag: commit} from `git ls-remote --tags`; annotated tags resolve to their peeled commit.
export function remoteTags(lsRemote) {
  const tags = {};
  for (const line of lsRemote.split('\n')) {
    if (!line.trim()) continue;
    const [oid, ref] = line.split('\t');
    const name = ref.replace(/^refs\/tags\//u, '');
    if (name.endsWith('^{}')) tags[name.slice(0, -3)] = oid;
    else tags[name] ??= oid;
  }
  return tags;
}

// {n: tag} of the locale/<patch>-<n> tags among `tags` (other names are ignored).
export function sequences(tags, patch) {
  const prefix = tagName(patch, '');
  const found = {};
  for (const tag of Object.keys(tags)) {
    const rest = tag.startsWith(prefix) ? tag.slice(prefix.length) : '';
    if (/^[1-9][0-9]*$/u.test(rest)) found[Number(rest)] = tag;
  }
  return found;
}

export const nextSequence = (tags, patch) => Math.max(0, ...Object.keys(sequences(tags, patch)).map(Number)) + 1;

const filePin = file => pin(readFileSync(file));

// Stage a release:build output directory's assets under out/assets, verified against the receipt.
export function stage(buildDir, out) {
  const receiptRaw = readFileSync(path.join(buildDir, 'receipt.json'));
  const receipt = strictJson(receiptRaw);
  require(receipt.schema === RECEIPT_SCHEMA, `${buildDir}/receipt.json: unexpected schema`);
  const asset = assetName(receipt.target.game_patch);
  require(receipt.package.asset === asset, `receipt.json names asset ${receipt.package.asset}, expected ${asset}`);
  const zip = readFileSync(path.join(buildDir, asset));
  require(samePin(pin(zip), receipt.package), `${asset} differs from its pin in receipt.json`);
  const members = readZip(zip);
  require(samePin(pin(members.get('manifest.json')?.raw ?? Buffer.alloc(0)), receipt.package.manifest),
    `${asset}: manifest.json differs from receipt.json`);
  if (existsSync(out)) {
    require(existsSync(path.join(out, MARKER)), `Refusing to replace a non-publish directory: ${out}`);
    rmSync(out, { recursive: true });
  }
  const assets = path.join(out, 'assets');
  mkdirSync(assets, { recursive: true });
  writeFileSync(path.join(out, MARKER), 'generated by src/locale-release-publish.mjs\n');
  writeFileSync(path.join(assets, asset), zip);
  writeFileSync(path.join(assets, 'receipt.json'), receiptRaw);
  const pins = { [asset]: pin(zip), 'receipt.json': pin(receiptRaw) };
  for (const [name, expected] of Object.entries(pins)) {
    require(samePin(filePin(path.join(assets, name)), expected), `Staged ${name} changed while copying`);
  }
  writeFileSync(path.join(assets, 'SHA256SUMS'), sha256sums(Object.fromEntries(Object.entries(pins).map(([n, p]) => [n, p.sha256]))));
  pins.SHA256SUMS = filePin(path.join(assets, 'SHA256SUMS'));
  const sorted = Object.fromEntries(Object.keys(pins).sort().map(name => [name, pins[name]]));
  return { directory: out, assets: sorted, receipt, asset };
}

export function releaseBody(staged, tag, sequence) {
  const { receipt, asset } = staged, { target, producer, source } = receipt;
  const zip = staged.assets[asset];
  const files = Object.keys(source.files);
  const languages = [...new Set(Object.keys(receipt.package.members).map(name => name.split('/')[3]))].sort();
  return `PoBR language package for ${target.game} ${target.game_patch} (${target.realm}), sequence ${sequence}.\n\n`
    + `- Producer: \`${producer.repository}@${producer.commit}\` (the commit \`${tag}\` names)\n`
    + `- Source: \`${source.manifest.path}\` (${source.manifest.bytes} bytes, SHA-256 \`${source.manifest.sha256}\`), `
    + `${files.length} pinned files, first published as \`${source.origin.tag}\` (\`${source.origin.revision}\`)\n`
    + `- \`${asset}\`: ${zip.bytes} bytes, SHA-256 \`${zip.sha256}\`; ${Object.keys(receipt.package.members).length} `
    + `i18n members (${languages.join(', ')}) with bytes identical to the source\n\n`
    + `Pin it in PoBR with \`mise run data:bump ${REPOSITORY} ${tag}\`. \`receipt.json\` records every source pin; `
    + '`SHA256SUMS` pins the other assets.\n\nGenerated by `mise run release:publish`.\n';
}

export function tagMessage(staged, tag) {
  const digests = Object.fromEntries(Object.entries(staged.assets).filter(([n]) => n !== 'SHA256SUMS').map(([n, p]) => [n, p.sha256]));
  return `PoBR language package ${staged.receipt.target.game_patch} (${tag})\n\n${sha256sums(digests)}`;
}

// The commands --yes runs, in order.
export function commands(staged, tag, commit, remote = REMOTE, repository = REPOSITORY) {
  const { directory } = staged;
  return [
    ['git', 'tag', '--annotate', '--file', path.join(directory, 'tag-message.txt'), tag, commit],
    ['git', 'push', remote, `refs/tags/${tag}`],
    ['gh', 'release', 'create', tag, '--repo', repository, '--verify-tag', '--title', tag,
      '--notes-file', path.join(directory, 'release-notes.md'), ...Object.keys(staged.assets).map(n => path.join(directory, 'assets', n))],
  ];
}

const quote = word => (/^[\w@%+=:,./-]+$/u.test(word) ? word : `'${word.replaceAll("'", "'\\''")}'`);
export const shellJoin = command => command.map(quote).join(' ');

// --- Git preflight -------------------------------------------------------------------------------

// HEAD must be a clean commit of <remote>/<branch>. A failed fetch is a warning (a real publish refuses it).
export function preflight(repo, { remote = REMOTE, branch = BRANCH, fetch = true } = {}) {
  const problems = [], warnings = [];
  const head = git(repo, ['rev-parse', '--verify', 'HEAD^{commit}']);
  require(head.status === 0, `${repo}: no HEAD commit`);
  const commit = head.stdout.trim();
  const status = git(repo, ['status', '--porcelain', '--untracked-files=all']).stdout.split('\n').filter(Boolean);
  if (status.length) problems.push(`the working tree is not clean (${status.length} paths, e.g. ${status[0].slice(3)})`);
  const tracking = `refs/remotes/${remote}/${branch}`;
  if (fetch) {
    const fetched = git(repo, ['fetch', '--quiet', '--no-tags', remote, `+refs/heads/${branch}:${tracking}`], { online: true });
    if (fetched.status) warnings.push(`could not fetch ${remote}/${branch} (${fetched.stderr}); using the local ref`);
  }
  const onBranch = git(repo, ['merge-base', '--is-ancestor', commit, tracking]).status;
  if (onBranch === 1) problems.push(`HEAD ${commit} is not on ${remote}/${branch}`);
  else if (onBranch) problems.push(`no ${remote}/${branch} ref to check HEAD against`);
  return { commit, problems, warnings };
}

// {tag: commit} of the remote's locale/* tags, or null when the remote cannot be listed.
export function listRemoteTags(repo, remote = REMOTE) {
  const result = git(repo, ['ls-remote', '--tags', remote, `refs/tags/${TAG_PREFIX}*`], { online: true });
  if (result.status) {
    say(`could not list ${remote}'s tags: ${result.stderr}`);
    return null;
  }
  return remoteTags(result.stdout);
}

// What publishing HEAD means: `new` (next <n>), `resume-push` (an unpushed local
// tag names HEAD), `remote-tag` (the remote already tags HEAD) or null (tags unknown).
export function plan(repo, patch, commit, tags) {
  if (tags === null) {
    return { action: null, sequence: null, problems: [`the remote's ${TAG_PREFIX}${patch}-* tags could not be listed, so <n> is unknown`] };
  }
  const remote = sequences(tags, patch);
  const atHead = Object.keys(remote).map(Number).filter(n => tags[remote[n]] === commit).sort((a, b) => a - b);
  if (atHead.length) {
    const problems = atHead.length > 1 ? [`HEAD carries several tags: ${atHead.map(n => remote[n])}`] : [];
    return { action: 'remote-tag', sequence: atHead.at(-1), problems };
  }
  const listed = git(repo, ['tag', '--points-at', commit, '--list', `${TAG_PREFIX}${patch}-*`]).stdout.split(/\s+/u).filter(Boolean);
  const local = Object.keys(sequences(Object.fromEntries(listed.map(t => [t, commit])), patch)).map(Number).sort((a, b) => a - b);
  if (local.length) {
    const problems = local.length > 1 ? [`HEAD carries several local tags: ${local.map(n => tagName(patch, n))}`] : [];
    problems.push(...local.filter(n => remote[n]).map(n => `${tagName(patch, n)} names another commit on the remote`));
    return { action: 'resume-push', sequence: local.at(-1), problems };
  }
  const sequence = nextSequence(tags, patch);
  const problems = [];
  if (git(repo, ['rev-parse', '--quiet', '--verify', `refs/tags/${tagName(patch, sequence)}`]).status === 0) {
    problems.push(`a local tag ${tagName(patch, sequence)} exists that the remote does not have; delete it`);
  }
  return { action: 'new', sequence, problems };
}

// --- GitHub --------------------------------------------------------------------------------------

export function defaultRunner(repo) {
  return (command, { capture = false } = {}) => {
    const result = spawnSync(command[0], command.slice(1), { cwd: repo, stdio: capture ? 'pipe' : 'inherit', maxBuffer: 1 << 26 });
    if (result.error) throw result.error;
    return { status: result.status, stdout: result.stdout ?? Buffer.alloc(0), stderr: result.stderr ?? Buffer.alloc(0) };
  };
}

export function ghProblem(run) {
  try {
    const result = run(['gh', 'auth', 'status'], { capture: true });
    return result.status === 0 ? null : `gh is not authenticated: ${result.stderr.toString().trim()}`;
  } catch (error) {
    return `gh is not available: ${error.message}`;
  }
}

// A Release's draft state and asset metadata, or null when there is none.
export function releaseState(run, tag, repository = REPOSITORY) {
  const result = run(['gh', 'release', 'view', tag, '--repo', repository, '--json', 'tagName,isDraft,assets'], { capture: true });
  if (result.status === 0) {
    const view = JSON.parse(result.stdout.toString());
    return { draft: view.isDraft === true, assets: view.assets ?? [] };
  }
  const stderr = result.stderr.toString();
  require(stderr.toLowerCase().includes('not found'), `gh release view ${tag} failed: ${stderr.trim()}`);
  return null;
}

// `gh release create` uploads into a draft first; an interrupted run leaves it behind.
// Null when the draft holds exactly the staged assets (finish it), else the remedy.
export function draftProblem(release, staged, tag, repository = REPOSITORY) {
  const found = Object.fromEntries(release.assets.map(asset => [asset.name, asset]));
  const differs = Object.entries(staged.assets).filter(([name, expected]) => {
    const asset = found[name];
    return !asset || asset.state !== 'uploaded' || asset.size !== expected.bytes || asset.digest !== `sha256:${expected.sha256}`;
  }).map(([name]) => name);
  differs.push(...Object.keys(found).filter(name => !staged.assets[name]));
  if (!differs.length) return null;
  return `${tag} is a draft Release whose assets are incomplete or differ from the staged ones (${differs.sort()}); `
    + `delete the draft with \`gh release delete ${tag} --repo ${repository} --yes\` (keeps the tag) and rerun`;
}

export const finishDraft = (tag, repository = REPOSITORY) => ['gh', 'release', 'edit', tag, '--repo', repository, '--draft=false'];

// {name: sha256} from a Release's SHA256SUMS, or null when the tag has no such Release.
export function releaseSums(run, tag, repository = REPOSITORY) {
  const result = run(['gh', 'release', 'download', tag, '--repo', repository, '--pattern', 'SHA256SUMS', '--output', '-'], { capture: true });
  if (result.status !== 0) {
    const stderr = result.stderr.toString();
    require(/not found|no assets match/iu.test(stderr), `gh release download ${tag} SHA256SUMS failed: ${stderr.trim()}`);
    return null;
  }
  return Object.fromEntries(result.stdout.toString().split('\n').filter(Boolean)
    .map(line => line.match(/^([0-9a-f]{64}) [ *](.+)$/u)).filter(Boolean).map(([, digest, name]) => [name, digest]));
}

// Download a Release's assets into `directory`; {name: pin}.
export function publishedAssets(run, tag, directory, repository = REPOSITORY) {
  rmSync(directory, { recursive: true, force: true });
  mkdirSync(directory, { recursive: true });
  const result = run(['gh', 'release', 'download', tag, '--repo', repository, '--dir', directory], { capture: true });
  require(result.status === 0, `gh release download ${tag} failed: ${result.stderr.toString().trim()}`);
  return Object.fromEntries(readdirSync(directory).sort().map(name => [name, filePin(path.join(directory, name))]));
}

// --- command -------------------------------------------------------------------------------------

// The release:build output for HEAD: rebuilt, or with --reuse the existing one if it matches this checkout.
function built(repo, configFile, reuse) {
  const loaded = loadConfig(configFile, repo);
  const out = path.join(repo, '.cache/release', targetName(loaded.config.target));
  if (reuse) {
    const receipt = strictJson(readFileSync(path.join(out, 'receipt.json')));
    const current = producerIdentity(repo, loaded);
    require(JSON.stringify(receipt.producer) === JSON.stringify(current), `${out} was not built from this checkout; rerun without --reuse`);
    say(`reusing ${out}`);
    return out;
  }
  say('running release:build');
  return build({ repo, config: configFile, out }).out;
}

const bullets = items => items.map(item => `  - ${item}\n`).join('');

export function main(argv = process.argv.slice(2), { repo = ROOT, runner, print = console.log } = {}) {
  const { values } = parseArgs({ args: argv, options: {
    config: { type: 'string' }, 'dry-run': { type: 'boolean' }, yes: { type: 'boolean' }, reuse: { type: 'boolean' },
    help: { type: 'boolean', short: 'h' },
  } });
  if (values.help) {
    print('usage: release:publish [--config release/<patch>.json] [--dry-run | --yes] [--reuse]');
    return 0;
  }
  require(!(values.yes && values['dry-run']), '--dry-run and --yes are mutually exclusive');
  const run = runner ?? defaultRunner(repo);
  // Before the build: the checkout, the remote's tags and (to publish) gh.
  const { commit, problems, warnings } = preflight(repo);
  const configFile = values.config ? path.resolve(values.config) : defaultConfig(repo);
  const { config } = loadConfig(configFile, repo);
  const patch = config.target.game_patch;
  const decision = plan(repo, patch, commit, listRemoteTags(repo));
  problems.push(...decision.problems);
  // Read-only in a dry run too: existing Releases are only visible through gh.
  const ghIssue = ghProblem(run);
  if (ghIssue) problems.push(ghIssue);
  if (values.yes && (problems.length || warnings.length)) {
    throw new Error(`refusing to publish:\n${bullets([...problems, ...warnings])}`);
  }
  // The build and what it says about HEAD.
  const staged = stage(built(repo, configFile, values.reuse), path.join(repo, '.cache/release/publish', targetName(config.target)));
  const { producer } = staged.receipt;
  if (producer.commit !== commit || producer.dirty) problems.push('the package was not built from a clean HEAD');
  const { action, sequence } = decision;
  if (config.published && !samePin(staged.assets[staged.asset], config.published)) {
    problems.push(`the package differs from the published ${config.published.tag} the config declares; update or drop "published"`);
  } else if (config.published && action === 'new') {
    problems.push(`these exact bytes are already published as ${config.published.tag}; nothing new to publish`);
  }
  const tag = tagName(patch, sequence ?? '<n>');
  const { directory } = staged;
  writeFileSync(path.join(directory, 'release-notes.md'), releaseBody(staged, tag, sequence ?? '<n>'));
  writeFileSync(path.join(directory, 'tag-message.txt'), tagMessage(staged, tag));
  let steps = commands(staged, tag, commit);
  let done = null;
  if (action === 'resume-push') steps = steps.slice(1);
  else if (action === 'remote-tag') {
    const release = ghIssue ? null : releaseState(run, tag);
    if (!release) steps = steps.slice(2);
    else if (release.draft) {
      const problem = draftProblem(release, staged, tag);
      if (problem) problems.push(problem);
      steps = problem ? [] : [finishDraft(tag)];
    } else {
      const published = publishedAssets(run, tag, path.join(directory, 'published'));
      require(JSON.stringify(published) === JSON.stringify(staged.assets),
        `${tag} is already released with other assets: ${Object.keys(published)} differ from the staged ${Object.keys(staged.assets)} (or their SHA-256)`);
      done = `already published: ${tag} names HEAD and its Release assets equal the staged ones`;
    }
  } else if (action === 'new' && sequence > 1 && !ghIssue) {
    // The same bytes never get a second number, whichever commit built them.
    const previous = tagName(patch, sequence - 1);
    if (releaseSums(run, previous)?.[staged.asset] === staged.assets[staged.asset].sha256) {
      problems.push(`these exact bytes are already published as ${previous}; pin that Release instead`);
    }
  }
  if (done) {
    print(done);
    for (const warning of warnings) print(`warning: ${warning}`);
    if (problems.length) print(`problems:\n${bullets(problems)}`);
    return problems.length ? 1 : 0;
  }

  print(`staged: ${directory}`);
  for (const [name, value] of Object.entries(staged.assets)) print(`  ${name}  ${value.bytes} bytes  sha256 ${value.sha256}`);
  print('SHA256SUMS:\n' + readFileSync(path.join(directory, 'assets/SHA256SUMS'), 'utf8').split('\n').filter(Boolean).map(l => `  ${l}\n`).join(''));
  const resumed = { 'resume-push': ' (tagged locally; resuming from the push)', 'remote-tag': ' (pushed; resuming)' }[action] ?? '';
  print(`tag: ${tag} -> ${commit}${resumed}`);
  print(`release body: ${path.join(directory, 'release-notes.md')}`);
  print(steps.length ? 'commands:\n' + steps.map(step => `  ${shellJoin(step)}\n`).join('')
    : 'commands: none until the problems below are resolved');
  for (const warning of warnings) print(`warning: ${warning}`);
  if (problems.length) {
    print(`publish refused:\n${bullets(problems)}`);
    return 1;
  }
  if (!values.yes) {
    print('dry run: nothing was tagged, pushed or released; rerun with --yes to publish');
    return 0;
  }
  for (const [index, step] of steps.entries()) {
    say(shellJoin(step));
    let failed;
    try {
      failed = run(step).status !== 0;
    } catch (error) {
      failed = error.message;
    }
    if (failed) {
      throw new Error(`step failed: ${shellJoin(step)}${typeof failed === 'string' ? ` (${failed})` : ''}\n`
        + 'rerun release:publish to resume (it keeps the tag), or run by hand:\n'
        + steps.slice(index).map(s => `  ${shellJoin(s)}\n`).join(''));
    }
  }
  print(`published https://github.com/${REPOSITORY}/releases/tag/${tag}`);
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.exitCode = main();
  } catch (error) {
    say(error.message);
    process.exitCode = 1;
  }
}
